-- 1. טבלת זירות דיון (topics)
CREATE TABLE IF NOT EXISTS public.topics (
  id TEXT PRIMARY KEY,
  slug TEXT,
  title TEXT NOT NULL,
  subtitle TEXT,
  organization TEXT NOT NULL,
  category TEXT NOT NULL DEFAULT 'municipal',
  groups_json JSONB NOT NULL DEFAULT '[]'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 2. טבלת היגדים והצעות פתרון (statements)
CREATE TABLE IF NOT EXISTS public.statements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  topic_id TEXT REFERENCES public.topics(id) ON DELETE CASCADE,
  text TEXT NOT NULL,
  author_group TEXT NOT NULL DEFAULT 'general',
  is_seed BOOLEAN NOT NULL DEFAULT false,
  status TEXT NOT NULL DEFAULT 'approved' CHECK (status IN ('approved', 'pending', 'rejected')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 3. טבלת הצבעות אנונימיות (votes)
CREATE TABLE IF NOT EXISTS public.votes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  topic_id TEXT REFERENCES public.topics(id) ON DELETE CASCADE,
  statement_id BIGINT REFERENCES public.statements(id) ON DELETE CASCADE,
  session_id TEXT NOT NULL,
  group_id TEXT NOT NULL,
  vote SMALLINT NOT NULL CHECK (vote IN (-1, 0, 1)),
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  UNIQUE(statement_id, session_id)
);

-- 4. טבלת תיעוד ובקרת סינון AI (moderation_logs)
CREATE TABLE IF NOT EXISTS public.moderation_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  original_text TEXT NOT NULL,
  suggested_text TEXT,
  passed BOOLEAN NOT NULL,
  is_rant BOOLEAN NOT NULL DEFAULT false,
  reason TEXT,
  topic_title TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- הפעלת הרשאות קריאה/כתיבה (Row Level Security / Public Access)
ALTER TABLE public.topics ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.statements ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.votes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.moderation_logs ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read access to topics" ON public.topics FOR SELECT USING (true);
CREATE POLICY "Allow public insert/update to topics" ON public.topics FOR ALL USING (true);

CREATE POLICY "Allow public read access to statements" ON public.statements FOR SELECT USING (true);
CREATE POLICY "Allow public insert to statements" ON public.statements FOR INSERT WITH CHECK (true);

CREATE POLICY "Allow public read/insert to votes" ON public.votes FOR ALL USING (true);
CREATE POLICY "Allow public insert to moderation_logs" ON public.moderation_logs FOR INSERT WITH CHECK (true);
