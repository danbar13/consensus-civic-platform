-- 1. טבלת זירות דיון (topics)
CREATE TABLE IF NOT EXISTS public.topics (
  id TEXT PRIMARY KEY,
  slug TEXT,
  title TEXT NOT NULL,
  subtitle TEXT,
  organization TEXT NOT NULL,
  category TEXT NOT NULL DEFAULT 'municipal',
  groups_json JSONB NOT NULL DEFAULT '[]'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  closes_at TIMESTAMPTZ
);

-- 2. טבלת היגדים והצעות פתרון (statements)
CREATE TABLE IF NOT EXISTS public.statements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  topic_id TEXT REFERENCES public.topics(id) ON DELETE CASCADE,
  text TEXT NOT NULL,
  author_group TEXT NOT NULL DEFAULT 'general',
  is_seed BOOLEAN NOT NULL DEFAULT false,
  status TEXT NOT NULL DEFAULT 'approved' CHECK (status IN ('approved', 'pending', 'rejected')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 3. טבלת הצבעות אנונימיות (votes)
CREATE TABLE IF NOT EXISTS public.votes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  topic_id TEXT REFERENCES public.topics(id) ON DELETE CASCADE,
  statement_id BIGINT REFERENCES public.statements(id) ON DELETE CASCADE,
  session_id TEXT NOT NULL,
  group_id TEXT NOT NULL,
  vote SMALLINT NOT NULL CHECK (vote IN (-1, 0, 1)),
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  UNIQUE(statement_id, session_id)
);

-- 4. טבלת לוגים, מעקב ביצועים ועלויות AI (ai_logs)
CREATE TABLE IF NOT EXISTS public.ai_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  action TEXT NOT NULL,
  model TEXT NOT NULL,
  duration_ms INTEGER NOT NULL,
  prompt_tokens INTEGER DEFAULT 0,
  candidates_tokens INTEGER DEFAULT 0,
  total_tokens INTEGER DEFAULT 0,
  estimated_cost_usd REAL DEFAULT 0,
  success INTEGER NOT NULL,
  error TEXT
);

-- =========================================================================
-- הרשאות גישה ומדיניות אבטחה (Row Level Security - RLS)
-- =========================================================================
ALTER TABLE public.topics ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.statements ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.votes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ai_logs ENABLE ROW LEVEL SECURITY;

-- מדיניות לזירות דיון: קריאה חופשית לכולם, עריכה/הוספה מורשית
DROP POLICY IF EXISTS "Allow public read access to topics" ON public.topics;
CREATE POLICY "Allow public read access to topics" ON public.topics FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow public insert/update to topics" ON public.topics;
CREATE POLICY "Allow public insert/update to topics" ON public.topics FOR ALL USING (true);

-- מדיניות להיגדים: קריאה חופשית של היגדים מאושרים/הכל, והוספת היגדים חדשים
DROP POLICY IF EXISTS "Allow public read access to statements" ON public.statements;
CREATE POLICY "Allow public read access to statements" ON public.statements FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow public insert/update to statements" ON public.statements;
CREATE POLICY "Allow public insert/update to statements" ON public.statements FOR ALL USING (true);

-- מדיניות להצבעות: קריאה והוספת הצבעות לכלל הגולשים
DROP POLICY IF EXISTS "Allow public all access to votes" ON public.votes;
CREATE POLICY "Allow public all access to votes" ON public.votes FOR ALL USING (true);

-- מדיניות ללוגים של AI: קריאה וכתיבה
DROP POLICY IF EXISTS "Allow public all access to ai_logs" ON public.ai_logs;
CREATE POLICY "Allow public all access to ai_logs" ON public.ai_logs FOR ALL USING (true);

-- אינדקסים לביצועים מרביים בעומס גולשים
CREATE INDEX IF NOT EXISTS idx_statements_topic_status ON public.statements(topic_id, status);
CREATE INDEX IF NOT EXISTS idx_votes_topic_statement ON public.votes(topic_id, statement_id);
CREATE INDEX IF NOT EXISTS idx_votes_session ON public.votes(session_id);
CREATE INDEX IF NOT EXISTS idx_ai_logs_created ON public.ai_logs(created_at DESC);
